// Bundles Leaflet into the app so the map screen has no runtime CDN dependency.
// Run: node scripts/gen-leaflet.mjs   (output is committed: src/ui/leafletAssets.ts)
import { readFileSync, writeFileSync } from 'node:fs';
const js = readFileSync('node_modules/leaflet/dist/leaflet.js', 'utf8');
const css = readFileSync('node_modules/leaflet/dist/leaflet.css', 'utf8');
if (js.includes('</script')) throw new Error('leaflet.js contains </script, cannot inline');
const out = `// AUTO-GENERATED by scripts/gen-leaflet.mjs from leaflet@1.9.4 (BSD-2-Clause). Do not edit.
export const LEAFLET_JS = ${JSON.stringify(js)};
export const LEAFLET_CSS = ${JSON.stringify(css)};
`;
writeFileSync('src/ui/leafletAssets.ts', out);
console.log('wrote src/ui/leafletAssets.ts', out.length, 'bytes');
