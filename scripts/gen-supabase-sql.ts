/**
 * Generates supabase/migrations/0001_tables.sql from src/db/registry.ts so the cloud schema
 * always matches the phone's SQLite schema.   Run: npm run gen:sql
 */
import { writeFileSync } from 'node:fs';
import { SYNCED_TABLES, TABLES, ColType } from '../src/db/registry';

const PG: Record<ColType, string> = {
  text: 'text', int: 'integer', real: 'double precision', bool: 'boolean',
  json: 'jsonb', date: 'date', ts: 'timestamptz', ref: 'uuid',
};

function pgDefault(type: ColType, def: string): string {
  if (type === 'int' || type === 'real') return String(Number(def));
  if (type === 'bool') return Number(def) ? 'true' : 'false';
  return `'${def.replace(/'/g, "''")}'`;
}

let sql = `-- AUTO-GENERATED by scripts/gen-supabase-sql.ts. Do not edit by hand; edit src/db/registry.ts and re-run.
-- Paal Pannai: synced tables (one owner per row, row level security on).

create or replace function public.touch_server_updated_at() returns trigger
language plpgsql as $$
begin
  new.server_updated_at := now();
  return new;
end $$;

`;

for (const name of SYNCED_TABLES) {
  const t = TABLES[name];
  const cols = t.cols.map(c => {
    let s = `  "${c.name}" ${PG[c.type]}`;
    if (c.notNull) s += ' not null';
    if (c.def !== undefined) s += ` default ${pgDefault(c.type, c.def)}`;
    return s;
  });
  sql += `create table if not exists public."${name}" (
  id uuid primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
${cols.join(',\n')},
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  server_updated_at timestamptz not null default now()
);
create index if not exists "${name}_sync_idx" on public."${name}" (owner_id, server_updated_at);
drop trigger if exists "${name}_touch" on public."${name}";
create trigger "${name}_touch" before insert or update on public."${name}"
  for each row execute function public.touch_server_updated_at();
alter table public."${name}" enable row level security;
drop policy if exists "${name}_owner_all" on public."${name}";
create policy "${name}_owner_all" on public."${name}" for all to authenticated
  using (owner_id = auth.uid()) with check (owner_id = auth.uid());

`;
}

writeFileSync('supabase/migrations/0001_tables.sql', sql);
console.log(`wrote supabase/migrations/0001_tables.sql (${SYNCED_TABLES.length} tables)`);
